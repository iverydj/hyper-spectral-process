"""Generate docs/api.md: every public function and class with its signature and the first docstring paragraph."""
import importlib
import inspect
import re
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent


@dataclass(frozen=True)
class AppConfig:
    out: Path = HERE / "api.md"
    modules: tuple = (
        "hyper_spectral_process.io.spectrum_map", "hyper_spectral_process.io.horiba",
        "hyper_spectral_process.io.nanobase", "hyper_spectral_process.io.ntmdt",
        "hyper_spectral_process.io.andor_sif", "hyper_spectral_process.io.axis",
        "hyper_spectral_process.preprocess.config", "hyper_spectral_process.preprocess.pipeline",
        "hyper_spectral_process.preprocess.runner", "hyper_spectral_process.preprocess.roi",
        "hyper_spectral_process.preprocess.despike", "hyper_spectral_process.preprocess.smooth",
        "hyper_spectral_process.preprocess.normalize", "hyper_spectral_process.preprocess.baseline",
        "hyper_spectral_process.preprocess.interpolate", "hyper_spectral_process.preprocess.derivative",
        "hyper_spectral_process.preprocess.augmentation", "hyper_spectral_process.preprocess.qa",
        "hyper_spectral_process.fit.lineshapes", "hyper_spectral_process.fit.specs",
        "hyper_spectral_process.fit.model", "hyper_spectral_process.fit.objective",
        "hyper_spectral_process.fit.engine", "hyper_spectral_process.fit.prepare",
        "hyper_spectral_process.fit.initial_guess", "hyper_spectral_process.fit.fit_map",
        "hyper_spectral_process.fit.variants", "hyper_spectral_process.fit.result",
        "hyper_spectral_process.fit.outputs", "hyper_spectral_process.plot.maps",
        "hyper_spectral_process.plot.spectra", "hyper_spectral_process.plot.summary",
        "hyper_spectral_process.plot.variants", "hyper_spectral_process.synthetic",
    )


def first_paragraph(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return " ".join(doc.split("\n\n")[0].split())


def signature(obj) -> str:
    """Signature text with the string annotations (``from __future__ import annotations``) unquoted."""
    try:
        text = str(inspect.signature(obj)).replace("\n", " ")
    except (TypeError, ValueError):
        return "(...)"
    text = re.sub(r": '([^']*)'", r": \1", text)
    return re.sub(r"-> (\"?)'([^']*)'\1", r"-> \2", text)


def main(cfg: AppConfig) -> None:
    lines = ["# API reference", "",
             "Generated by `docs/make_api.py` from the docstrings (first paragraph of each). "
             "Import paths: `hyper_spectral_process.<subpackage>`; every name below is also exported by its "
             "subpackage (`from hyper_spectral_process.fit import fit_map`).", ""]
    for name in cfg.modules:
        mod = importlib.import_module(name)
        lines += [f"## `{name}`", "", first_paragraph(mod), ""]
        for attr, obj in vars(mod).items():
            if attr.startswith("_") or getattr(obj, "__module__", None) != name:
                continue
            if inspect.isclass(obj):
                lines.append(f"- **class `{attr}{signature(obj)}`**: {first_paragraph(obj)}")
                for m_name, m in vars(obj).items():
                    if m_name.startswith("_") or not (inspect.isfunction(m) or isinstance(m, (classmethod, property))):
                        continue
                    target = m.__func__ if isinstance(m, classmethod) else (m.fget if isinstance(m, property) else m)
                    sig = "" if isinstance(m, property) else signature(target)
                    lines.append(f"    - `{m_name}{sig}`: {first_paragraph(target)}")
            elif inspect.isfunction(obj):
                lines.append(f"- `{attr}{signature(obj)}`: {first_paragraph(obj)}")
        lines.append("")
    cfg.out.write_text("\n".join(lines))
    print(f"wrote {cfg.out}")


if __name__ == "__main__":
    main(AppConfig())
